import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createPlugin } from '../plugins/alert-hub/application.js';
import { createCustomPluginRuntime } from '../server/plugins/custom-runtime.js';
import { createWorkspaceTodos } from '../server/workspace-todos.js';
import { createPluginApplications } from '../server/plugins/applications.js';
const config = { endpoint: 'https://hub.example', command: '/test/mcp', username: 'demo', password: 'fake-secret' };
function mock() {
 const calls: any[] = []; let closed = 0;
 const client = { listTools: async () => [{ name: 'get_me', annotations: {readOnlyHint:true}, inputSchema:{} }, {name:'ack_case',annotations:{readOnlyHint:true},inputSchema:{}}], callTool: async (name: string,args: unknown) => { calls.push({name,args}); return {structuredContent:{ok:true}}; }, close: async () => {closed++} };
 const plugin = createPlugin({dataDirectory:'',workspaceDirectory:'',configuration:config,mcp:{connect:async options => {assert.equal(options.env?.ALERT_HUB_MCP_PASSWORD,config.password);return client}}});
 return { plugin,calls,client,closed:()=>closed };
}
test('MCP configuration, audited reads and single-use argument-bound write confirmation',async()=>{
 const {plugin,calls,closed}=mock();
 assert.equal((await plugin.request('status')).configured,true);
 assert.equal(JSON.stringify(await plugin.request('status')).includes(config.password),false);
 await plugin.request('read',{name:'get_me'});assert.equal(calls.length,1);
 await assert.rejects(plugin.request('read',{name:'ack_case',arguments:{id:'c1'}}),/预览/);
 const input={name:'ack_case',arguments:{id:'c1'}};
 const preview=await plugin.request('prepare',input);assert.equal(calls.length,1);
 await assert.rejects(plugin.request('commit',{...preview,arguments:{id:'c2'}}),/确认/);
 await assert.rejects(plugin.request('commit',preview),/确认/);
 const fresh=await plugin.request('prepare',input);await plugin.request('commit',fresh);assert.equal(calls.length,2);
 await assert.rejects(plugin.request('commit',fresh),/确认/);
 await plugin.close();assert.equal(closed(),1);
});
test('missing config blocks connection; MCP errors are shown and credentials redacted',async()=>{
 const empty=createPlugin({configuration:{},mcp:{connect:async()=>{throw Error('must not connect')}},dataDirectory:'',workspaceDirectory:''});
 await assert.rejects(empty.request('tools'),/配置/);
 const {plugin,client}=mock(); client.callTool=async()=>({isError:true,content:[{type:'text',text:'server message fake-secret'}]}) as any;
 await assert.rejects(plugin.request('read',{name:'get_me'}),e=>e instanceof Error && e.message==='server message [已隐藏]');
});
test('package installs, configuration is masked and durable, compatible upgrade keeps state',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'ah-plugin-'));
 const todos=await createWorkspaceTodos(path.join(root,'todos')), runtime=await createCustomPluginRuntime(path.join(root,'plugins'),todos), apps=createPluginApplications(runtime,async()=>{});
 t.after(async()=>{await apps.close();await runtime.close();await fs.rm(root,{recursive:true,force:true})});
 const directory=path.resolve('plugins/alert-hub/package'), inspected=await runtime.inspect(directory);
 const input={directory,digest:inspected.digest,grants:inspected.manifest.permissions,confirmed:true,trustedLocalCode:true,showInMenu:true};
 await runtime.install(input);
 assert.equal((await apps.call('alert-hub',{method:'status'}) as any).configured,false);
 const before=await runtime.configuration('alert-hub');
 const saved=await runtime.configure('alert-hub',{revision:before.revision,values:config});apps.stop('alert-hub');
 assert.equal(JSON.stringify(saved).includes(config.password),false);assert.equal(saved.secrets.password,true);
 assert.equal((await apps.call('alert-hub',{method:'status'}) as any).configured,true);
 await assert.rejects(runtime.configure('alert-hub',{revision:before.revision,values:{username:'stale'}}),/配置已变化/);
 await assert.rejects(runtime.configure('alert-hub',{revision:saved.revision,values:{password:'',username:'new'}}),/密码/);
 await runtime.configure('alert-hub',{revision:saved.revision,values:{password:config.password,username:'new'}});
 const retained=await runtime.configuration('alert-hub');await runtime.configure('alert-hub',{revision:retained.revision,values:{password:''}});
 assert.equal((await runtime.applicationConfiguration('alert-hub')).password,config.password);
 assert.equal((await fs.stat(path.join(root,'plugins/configuration/alert-hub.json'))).mode & 0o777,0o600);
 await runtime.change('alert-hub',{enabled:false,showInMenu:false});apps.stop('alert-hub');assert.throws(()=>apps.call('alert-hub',{method:'status'}),/停用/);
 const next=path.join(root,'next');await fs.cp(directory,next,{recursive:true});
 const manifest=JSON.parse(await fs.readFile(path.join(next,'plugin.json'),'utf8'));manifest.version=manifest.version.split('.').map((n:string,i:number)=>i===2?Number(n)+1:n).join('.');await fs.writeFile(path.join(next,'plugin.json'),JSON.stringify(manifest));
 const upgrade=await runtime.inspect(next);await runtime.install({...input,directory:next,digest:upgrade.digest,replaceDigest:inspected.digest});
 const installed=runtime.list().plugins[0];assert.equal(installed.enabled,false);assert.equal(installed.showInMenu,false);assert.deepEqual(installed.grants,input.grants);
 await assert.rejects(runtime.install({...input,directory:next,digest:upgrade.digest,replaceDigest:inspected.digest}),/版本变化/);
 const reloaded=await createCustomPluginRuntime(path.join(root,'plugins'),todos);assert.equal((await reloaded.configuration('alert-hub')).values.username,'new');assert.equal((await reloaded.configuration('alert-hub')).secrets.password,true);
 await runtime.change('alert-hub',{remove:true});await assert.rejects(runtime.configuration('alert-hub'),/移除/);
 await runtime.install({...input,directory:next,digest:upgrade.digest});assert.equal((await runtime.applicationConfiguration('alert-hub')).password,config.password);
});

test('configuration routes reject foreign origin and stop only the changed application', async t => {
 const {createCustomPluginRoutes}=await import('../server/plugins/custom-routes.js');
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'plugin-config-route-'));
 const runtime=await createCustomPluginRuntime(path.join(root,'plugins'),await createWorkspaceTodos(path.join(root,'todos')));
 t.after(async()=>{await runtime.close();await fs.rm(root,{recursive:true,force:true})});
 const directory=path.resolve('plugins/alert-hub/package'),p=await runtime.inspect(directory);
 await runtime.install({directory,digest:p.digest,grants:p.manifest.permissions,confirmed:true,trustedLocalCode:true});
 let status=0,result:any,body:any;const stopped:string[]=[];
 const route=createCustomPluginRoutes(runtime,{} as any,{port:5317,examples:[],citations:()=>[],applications:{stop:(id:string)=>stopped.push(id)} as any,json(_r,s,v){status=s;result=v},body:async()=>body});
 const req:any={method:'POST',socket:{remoteAddress:'127.0.0.1'},headers:{host:'localhost:5317',origin:'http://localhost:5317','content-type':'application/json','x-delivery-confirmed':'yes'}};
 const url=new URL('http://localhost:5317/api/custom-plugins/alert-hub/configure');
 body={revision:(await runtime.configuration('alert-hub')).revision,values:config};
 await route({...req,headers:{...req.headers,origin:'https://other.test'}},{} as any,url);assert.equal(status,403);assert.equal(stopped.length,0);
 await route(req,{} as any,url);assert.equal(status,200);assert.deepEqual(stopped,['alert-hub']);assert.equal(JSON.stringify(result).includes(config.password),false);
 await route({...req,method:'GET'},{} as any,new URL('http://localhost:5317/api/custom-plugins/alert-hub/configuration'));assert.equal(result.secrets.password,true);assert.equal(result.values.password,undefined);
});
